"""In-process INDEX.md regeneration core.

The single source of INDEX.md regeneration: the store/legacy reindex logic
that every mutating verb calls in-process (via
``reindex.reindex_after_mutation``) and that ``issue admin reindex`` calls
directly. There is no sibling-binary subprocess and no name resolution,
which structurally eliminates the failure class where an installed binary
silently skipped reindex because the sibling name did not match.

Renders INDEX.md deterministically from frontmatter: ``STATUS_ORDER`` group
order, table shapes, the changelog-column rule, the header comment,
``atomic_write`` for the store path, and the store index-lock + per-mutation
``reindex INDEX.md`` commit semantics.
"""

from __future__ import annotations

import re
from datetime import date
from pathlib import Path

import concurrency
from concurrency import atomic_write

STATUS_ORDER = ["in-progress", "open", "blocked", "done", "cancelled"]
STATUS_LABELS = {
    "in-progress": "In Progress",
    "open": "Open",
    "blocked": "Blocked",
    "done": "Done",
    "cancelled": "Cancelled",
}

PREFIX_RE = re.compile(r"^[A-Z][A-Z0-9]{1,7}$")

_REQUIRED = ("id", "title", "type", "status", "priority", "updated")


def parse_frontmatter(path: Path):
    """Parse an issue file's frontmatter, or None if malformed/unreadable.

    Matches the store generator's tolerant read (OSError -> None); the
    legacy generator read without the guard, but an unreadable file mid-glob
    is pathological and the rendered output is unaffected.
    """
    try:
        text = path.read_text()
    except OSError:
        return None
    m = re.match(r"^---\s*\n(.*?)\n---", text, re.DOTALL)
    if not m:
        return None
    fields = {}
    for line in m.group(1).splitlines():
        kv = line.split(":", 1)
        if len(kv) == 2:
            fields[kv[0].strip()] = kv[1].strip().strip('"')
    if not all(k in fields for k in _REQUIRED):
        return None
    return fields


def _header(title):
    return [
        f"# {title}",
        "",
        f"<!-- Regenerated by reindex-issues on {date.today()}. Do not edit by hand. -->",
        "",
    ]


def render_status_sections(groups):
    lines = []
    done_has_skip = any(
        f.get("changelog", "") == "skip" for f in groups.get("done", [])
    )
    for status in STATUS_ORDER:
        lines.append(f"## {STATUS_LABELS[status]}")
        lines.append("")
        rows = groups.get(status, [])
        if status == "done" and done_has_skip:
            lines.append("| ID | Title | Type | Priority | Updated | Changelog |")
            lines.append("|----|-------|------|----------|---------|-----------|")
            for f in rows:
                cl = f.get("changelog", "")
                lines.append(
                    f"| {f['id']} | {f['title']} | {f['type']} | "
                    f"{f['priority']} | {f['updated']} | {cl} |"
                )
        else:
            lines.append("| ID | Title | Type | Priority | Updated |")
            lines.append("|----|-------|------|----------|---------|")
            for f in rows:
                lines.append(
                    f"| {f['id']} | {f['title']} | {f['type']} | "
                    f"{f['priority']} | {f['updated']} |"
                )
        lines.append("")
    return lines


def reindex_store(store_root, *, suppress_commit: bool = False) -> str:
    """Regenerate the store root + every per-prefix INDEX.md in-process.

    Under the store index lock, exactly like the bash wrapper. When
    ``suppress_commit`` is False the writes are wrapped in the per-mutation
    ``reindex INDEX.md`` store commit; when True (an outer mutation owns the
    commit) the writes run bare. Returns the summary line the flat binary
    printed on stdout.
    """
    store_root = Path(str(store_root).rstrip("/"))
    if not store_root.is_dir():
        raise FileNotFoundError(f"store directory not found: {store_root}")

    prefix_dirs = sorted(
        d for d in store_root.iterdir() if d.is_dir() and PREFIX_RE.match(d.name)
    )

    def do_writes():
        aggregate = {s: [] for s in STATUS_ORDER}
        per_prefix = []
        total = 0
        for pdir in prefix_dirs:
            groups = {s: [] for s in STATUS_ORDER}
            count = 0
            for f in sorted(pdir.glob("*.md")):
                if f.name == "INDEX.md" or f.stem.endswith("-TEMPLATE"):
                    continue
                fields = parse_frontmatter(f)
                if not fields:
                    continue
                status = fields["status"]
                if status in groups:
                    groups[status].append(fields)
                    aggregate[status].append(fields)
                    count += 1
                    total += 1
            per_prefix_index = pdir / "INDEX.md"
            body = _header(f"Issues Index -- {pdir.name}") + render_status_sections(groups)
            atomic_write(per_prefix_index, "\n".join(body))
            per_prefix.append((pdir.name, count))

        root_lines = _header("Issues Index")
        root_lines.append("## Prefixes")
        root_lines.append("")
        if per_prefix:
            root_lines.append("| Prefix | Issues | Index |")
            root_lines.append("|--------|--------|-------|")
            for name, n in per_prefix:
                root_lines.append(
                    f"| {name} | {n} | [`{name}/INDEX.md`](./{name}/INDEX.md) |"
                )
        else:
            root_lines.append("_(no prefix directories found)_")
        root_lines.append("")
        root_lines.append("## Aggregate")
        root_lines.append("")
        root_lines.extend(render_status_sections(aggregate))
        atomic_write(store_root / "INDEX.md", "\n".join(root_lines))
        return per_prefix, total

    with concurrency.index_lock(store_root):
        if suppress_commit:
            per_prefix, total = do_writes()
        else:
            commit_paths = ["INDEX.md"] + [
                f"{p.name}/INDEX.md" for p in prefix_dirs
            ]
            with concurrency.store_mutation(store_root, commit_paths, "reindex INDEX.md"):
                per_prefix, total = do_writes()

    return (
        f"Reindexed {store_root}/INDEX.md and {len(per_prefix)} "
        f"per-prefix index(es) -- {total} issue(s) total."
    )


def reindex_legacy_dir(issues_dir) -> str:
    """Regenerate a single legacy ``.issues/INDEX.md`` in-process.

    Preserved verbatim from the v1.5.1 generator: plain ``write_text`` (no
    lock, no store commit), and the em-dash summary line the legacy binary
    printed.
    """
    issues_dir = Path(str(issues_dir).rstrip("/"))
    if not issues_dir.is_dir():
        raise FileNotFoundError(f"directory not found: {issues_dir}")
    index_path = issues_dir / "INDEX.md"

    groups = {s: [] for s in STATUS_ORDER}
    count = 0
    for f in sorted(issues_dir.glob("*.md")):
        if f.name == "INDEX.md" or f.stem.endswith("-TEMPLATE"):
            continue
        fields = parse_frontmatter(f)
        if not fields:
            continue
        status = fields["status"]
        if status in groups:
            groups[status].append(fields)
            count += 1

    lines = [
        "# Issues Index",
        "",
        f"<!-- Regenerated by reindex-issues on {date.today()}. Do not edit by hand. -->",
        "",
    ]
    lines.extend(render_status_sections(groups))
    index_path.write_text("\n".join(lines))
    return f"Reindexed {index_path} — {count} issue(s) found."
